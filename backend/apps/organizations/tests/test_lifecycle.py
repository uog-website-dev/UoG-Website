def install_site_writer_guards():
    # This is the required future Site-migration integration protocol. The
    # production Site model/status storage does not exist in this repository.
    with connections["default"].cursor() as cursor:
        cursor.execute("""
            CREATE TRIGGER test_site_serialization BEFORE INSERT OR UPDATE OR DELETE
                ON organizations_test_site FOR EACH STATEMENT EXECUTE FUNCTION organizations_serialize_hierarchy();
            CREATE FUNCTION organizations_test_check_site_unit()
            RETURNS trigger LANGUAGE plpgsql VOLATILE AS $$
            BEGIN
                IF NEW.status = 'ACTIVE' AND NOT EXISTS (
                    SELECT 1 FROM organizations_organizationunit WHERE id=NEW.organization_unit_id AND status='ACTIVE'
                ) THEN
                    RAISE EXCEPTION 'An active Site requires an active organization.' USING ERRCODE='23514';
                END IF;
                RETURN NEW;
            END;
            $$;
            CREATE TRIGGER test_site_status AFTER INSERT OR UPDATE ON organizations_test_site
                FOR EACH ROW EXECUTE FUNCTION organizations_test_check_site_unit();
        """)


def test_forward_lifecycle_and_archived_identity_are_preserved(organization):
    root, unit = organization
    with pytest.raises(ValidationError):
        archive_unit(unit.pk)  # Explicit deactivation is mandatory.
    assert deactivate_unit(unit.pk).status == "INACTIVE"
    assert archive_unit(unit.pk).status == "ARCHIVED"
    for status in ("ACTIVE", "INACTIVE"):
        with pytest.raises(ValidationError):
            transition_unit(unit.pk, status=status)
    archived = OrganizationUnit.objects.get(pk=unit.pk)
    archived.name = "Corrected historical label"
    archived.save(update_fields=["name"])
    archived.refresh_from_db()
    assert archived.parent_id == root.pk and archived.code == "CI"
    assert archived.status == "ARCHIVED"
    assert archive_unit(unit.pk).pk == unit.pk  # Idempotent, not a backward transition.


