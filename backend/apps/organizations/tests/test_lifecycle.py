@pytest.mark.django_db(transaction=True)
@pytest.mark.parametrize("legacy_problem", ["non_university_root", "inactive_parent_active_child"])
def test_migration_rejects_invalid_legacy_rules_without_rewriting_records(legacy_problem):
    connection = connections["default"]
    old_target = [("organizations", "0004_hierarchy_integrity")]
    new_target = [("organizations", "0005_lifecycle_rules")]
    executor = MigrationExecutor(connection)
    latest_targets = executor.loader.graph.leaf_nodes()
    executor.migrate(old_target)
    historical_apps = executor.loader.project_state(old_target).apps
    OldType = historical_apps.get_model("organizations", "OrganizationType")
    OldUnit = historical_apps.get_model("organizations", "OrganizationUnit")
    root = None
    try:
        university, _ = OldType.objects.get_or_create(code="UNIVERSITY", defaults={"name": "University"})
        college, _ = OldType.objects.get_or_create(code="COLLEGE", defaults={"name": "College"})
        root = OldUnit.objects.create(code="LEGACY_ROOT", name="Root", organization_type=university)
        parent = OldUnit.objects.create(code="LEGACY_PARENT", name="Parent", organization_type=college, parent=root)
        OldUnit.objects.create(code="LEGACY_CHILD", name="Child", organization_type=college, parent=parent)
        if legacy_problem == "non_university_root":
            OldUnit.objects.filter(pk=root.pk).update(organization_type_id=college.pk)
        else:
            OldUnit.objects.filter(pk=parent.pk).update(status="INACTIVE")
        with pytest.raises(IntegrityError):
            MigrationExecutor(connection).migrate(new_target)
        assert OldUnit.objects.count() == 3
    finally:
        if root is not None:
            OldUnit.objects.update(status="ACTIVE")
            OldUnit.objects.filter(pk=root.pk).update(organization_type_id=university.pk)
        MigrationExecutor(connection).migrate(latest_targets)


@pytest.mark.django_db(transaction=True)
@pytest.mark.parametrize("dependency", ["child", "site"])
def test_deactivation_race_with_new_active_dependency_is_serialized(organization, site_contract, dependency):
    _, unit = organization
    install_site_writer_guards()
    barrier = Barrier(3)

    def attempt(action):
        close_old_connections()
        try:
            with transaction.atomic():
                with connections["default"].cursor() as cursor:
                    cursor.execute("SET LOCAL lock_timeout='5s'")
                    cursor.execute("SET LOCAL statement_timeout='10s'")
                barrier.wait(timeout=10)
                if action == "deactivate":
                    deactivate_unit(unit.pk)
                elif dependency == "site":
                    link_site(unit.pk)
                else:
                    OrganizationUnit.objects.create(code="CONCURRENT_CHILD", name="Child", parent_id=unit.pk, organization_type_id=unit.organization_type_id)
            return "committed"
        except ValidationError:
            return "validation"
        except IntegrityError as exc:
            assert getattr(exc.__cause__, "sqlstate", None) == "23514"
            return "validation"
        finally:
            connections.close_all()

    try:
        with ThreadPoolExecutor(max_workers=2) as executor:
            futures = [executor.submit(attempt, action) for action in ("deactivate", "reference")]
            barrier.wait(timeout=10)
            assert sorted(future.result(timeout=20) for future in futures) == ["committed", "validation"]
        unit.refresh_from_db()
        if unit.status == "INACTIVE":
            assert not unit.children.filter(status="ACTIVE").exists()
            with connections["default"].cursor() as cursor:
                cursor.execute("SELECT count(*) FROM organizations_test_site WHERE status='ACTIVE'")
                assert cursor.fetchone()[0] == 0
    finally:
        with connections["default"].cursor() as cursor:
            cursor.execute("DROP TRIGGER test_site_status ON organizations_test_site")
            cursor.execute("DROP FUNCTION organizations_test_check_site_unit()")
