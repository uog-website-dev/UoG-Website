def test_database_status_rules_and_delete_policy_cannot_be_bypassed(organization):
    _, unit = organization
    with pytest.raises(IntegrityError), transaction.atomic():
        OrganizationUnit.objects.filter(pk=unit.pk).update(status="ARCHIVED")
    deactivate_unit(unit.pk)
    with pytest.raises(IntegrityError), transaction.atomic():
        OrganizationUnit.objects.filter(pk=unit.pk).update(status="ACTIVE")
    archive_unit(unit.pk)
    with pytest.raises(IntegrityError), transaction.atomic():
        OrganizationUnit.objects.filter(pk=unit.pk).delete()
    assert not admin.site._registry[OrganizationUnit].has_delete_permission(None, unit)


def test_historical_references_are_retained_and_cascade_deletion_is_blocked(organization):
    _, unit = organization
    with connections["default"].cursor() as cursor:
        cursor.execute("CREATE TABLE history_reference(unit_id bigint REFERENCES organizations_organizationunit(id) ON DELETE CASCADE)")
        cursor.execute("INSERT INTO history_reference VALUES (%s)", [unit.pk])
    deactivate_unit(unit.pk)
    archive_unit(unit.pk)
    for action in (lambda: unit.delete(), lambda: delete_unit(unit.pk)):
        with pytest.raises(ValidationError):
            action()
    with pytest.raises(IntegrityError), transaction.atomic(), connections["default"].cursor() as cursor:
        cursor.execute("DELETE FROM organizations_organizationunit WHERE id=%s", [unit.pk])
    with connections["default"].cursor() as cursor:
        cursor.execute("SELECT unit_id FROM history_reference")
        assert cursor.fetchall() == [(unit.pk,)]


